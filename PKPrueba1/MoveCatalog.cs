    // Movimientos por nombre.
    private static readonly Dictionary<string, PokemonMove> Moves = new();
    // Nombre de cada movimiento a partir de su id.
    private static readonly Dictionary<int, string> NamesById = new();

    // Constructor estático: convierte cada línea de datos en un movimiento.
    static MoveCatalog()
    {
        foreach (string line in Raw)
        {
            string[] p = line.Split('|');
            int id = int.Parse(p[0]);

            Moves[p[1]] = new PokemonMove(
                p[1],
                int.Parse(p[4]),
                int.Parse(p[5]),
                p[2],
                p[3],
                p.Length > 6 ? p[6] : "");

            NamesById[id] = p[1];
        }
    }

    // Indica si existe un movimiento con ese nombre.
    public static bool Exists(string name) => Moves.ContainsKey(name);

    // Todos los movimientos del catálogo.
    public static IEnumerable<PokemonMove> All => Moves.Values;

    // Devuelve el nombre del movimiento con ese id (null si no existe).
    public static string? NameOf(int id) => NamesById.TryGetValue(id, out string? name) ? name : null;

    // Devuelve una copia nueva del movimiento (null si no existe), para que cada Pokémon tenga la suya.
    public static PokemonMove? Create(string name)
    {
        return Moves.TryGetValue(name, out PokemonMove? move) ? move.Clone() : null;
    }
